import { z } from 'zod';
import type { UiMessage } from '../../ai/agent.types.js';
import { MAX_MESSAGE_LENGTH } from '../../guardrails/input-checks/length.check.js';
import { photoKeySchema } from '../../storage/dto/storage.schemas.js';

export const sessionIdSchema = z.uuid({ message: 'Invalid session id' });
export const draftIdSchema = z.uuid({ message: 'Invalid draft id' });

export const sendMessageSchema = z.object({
  // The guardrail does the real checks; this just rejects obviously bad requests early
  text: z.string().max(MAX_MESSAGE_LENGTH + 500),
  photoKeys: z.array(photoKeySchema).max(5).optional(),
  /** Optional: the citizen's current position from the browser (Geolocation API), shared with a tap */
  location: z
    .object({
      latitude: z.number().min(-90).max(90),
      longitude: z.number().min(-180).max(180),
      /** Browser's accuracy estimate in metres */
      accuracyMeters: z.number().min(0).max(100_000).optional(),
    })
    .optional(),
});

export const submitDraftSchema = z.object({
  /** Generated by the frontend once per draft card — makes Submit safe to retry */
  idempotencyKey: z.uuid(),
});

export type SendMessageDto = z.infer<typeof sendMessageSchema>;
export type SubmitDraftDto = z.infer<typeof submitDraftSchema>;

export interface ChatMessageView extends UiMessage {
  id: string;
  role: 'USER' | 'ASSISTANT';
  createdAt: Date;
}

export interface ChatTurnResponse {
  sessionId: string;
  messages: ChatMessageView[];
  awaitingConfirmation: boolean;
  draftId: string | null;
}
